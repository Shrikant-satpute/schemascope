using System.Runtime.CompilerServices;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using SchemaScope.Core.Model;
using SchemaScope.Scripting;
using SchemaScope.SqlServer;

namespace SchemaScope.Tests;

/// <summary>
/// Regression nets for the multi-database work (MULTI-DATABASE-PLAN §9): what the SQL Server reader makes of a fixed
/// schema, and every file of a full generator run, pinned before anything was changed. A change to either is a
/// regression until it is explained - these files are never regenerated to make a test pass.
/// </summary>
public class GoldenTests
{
    private static string GoldenPath(string name, [CallerFilePath] string here = "") =>
        Path.Combine(Path.GetDirectoryName(here)!, "Golden", name);

    /// <summary>Set SCHEMASCOPE_WRITE_GOLDEN=1 to write a missing golden file; an existing one is never overwritten.</summary>
    private static void AssertGolden(string name, string actual)
    {
        var path = GoldenPath(name);
        if (!File.Exists(path) && Environment.GetEnvironmentVariable("SCHEMASCOPE_WRITE_GOLDEN") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, actual, new UTF8Encoding(false));
        }
        Assert.True(File.Exists(path), $"{path} is missing.");
        Assert.Equal(File.ReadAllText(path).ReplaceLineEndings("\n"), actual.ReplaceLineEndings("\n"));
    }

    /// <summary>The same digest as DestructiveSectionTests: every file (path + text), with the date and probe noise blanked.</summary>
    private static string Digest(string root)
    {
        var sb = new StringBuilder();
        foreach (var f in Directory.GetFiles(root, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
        {
            var rel = Path.GetRelativePath(root, f).Replace('\\', '/');
            var text = File.ReadAllText(f);
            if (rel == "README.md")
                text = string.Join("\n", text.Split('\n').Where(l =>
                    !l.StartsWith("Generated by SchemaScope on ", StringComparison.Ordinal) && !l.Contains(" not checked (", StringComparison.Ordinal)));
            text = Regex.Replace(text, @"(Msg -?\d+: |timed out).*", "PROBE FAILED");
            sb.Append(rel).Append('\0').Append(text).Append('\0');
        }
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString())));
    }

    [Fact]
    public async Task A_full_run_with_every_section_and_destructive_is_unchanged()
    {
        using var folder = new TempFolder();
        var o = ObjectFixture.Options(folder.Path);
        o.OnlyObjects = null;
        o.IncludeDestructive = true;
        var outcome = await ObjectFixture.Generator().GenerateAsync(ObjectFixture.Source, ObjectFixture.Target, o, new HashSet<string>(), default,
            differentCandidates: new Dictionary<string, LineChange> { ["dbo.p_diff"] = new(1, 1) });
        Assert.True(outcome.Success, outcome.Message);
        Assert.Equal("48D1B8D5C233D44F7D94C98C40AD79C83D185EDC2711145204C915AAA0E686DE", Digest(outcome.Path!));
    }

    /// <summary>Every object kind the reader knows, all constraints named, so nothing depends on a generated name.</summary>
    private const string Schema = """
        CREATE SCHEMA sales AUTHORIZATION dbo;
        GO
        CREATE TYPE dbo.Code FROM varchar(12) NOT NULL;
        GO
        CREATE TYPE dbo.IdList AS TABLE (Id int NOT NULL, Note nvarchar(20) NULL);
        GO
        CREATE SEQUENCE dbo.OrderNo AS bigint START WITH 1000 INCREMENT BY 5;
        GO
        CREATE TABLE dbo.Customer (
            Id int IDENTITY(1,1) NOT NULL CONSTRAINT PK_Customer PRIMARY KEY CLUSTERED,
            Code dbo.Code NOT NULL CONSTRAINT UQ_Customer_Code UNIQUE,
            Name nvarchar(100) COLLATE Latin1_General_CS_AS NULL,
            Created datetime2(3) NOT NULL CONSTRAINT DF_Customer_Created DEFAULT (sysutcdatetime()),
            Credit decimal(12,2) NOT NULL CONSTRAINT DF_Customer_Credit DEFAULT ((0)),
            Upper AS (upper(Name)),
            CONSTRAINT CK_Customer_Credit CHECK (Credit >= 0));
        CREATE TABLE sales.Orders (
            Id bigint NOT NULL CONSTRAINT DF_Orders_Id DEFAULT (NEXT VALUE FOR dbo.OrderNo),
            CustomerId int NOT NULL,
            Total money NULL,
            Status tinyint NOT NULL CONSTRAINT DF_Orders_Status DEFAULT ((1)),
            Payload varbinary(max) NULL,
            Ref uniqueidentifier ROWGUIDCOL NOT NULL CONSTRAINT DF_Orders_Ref DEFAULT (newid()),
            CONSTRAINT PK_Orders PRIMARY KEY NONCLUSTERED (Id),
            CONSTRAINT FK_Orders_Customer FOREIGN KEY (CustomerId) REFERENCES dbo.Customer (Id) ON DELETE CASCADE);
        CREATE CLUSTERED INDEX CIX_Orders_Customer ON sales.Orders (CustomerId);
        CREATE NONCLUSTERED INDEX IX_Orders_Status ON sales.Orders (Status DESC) INCLUDE (Total) WHERE Status > 0;
        ALTER TABLE sales.Orders NOCHECK CONSTRAINT FK_Orders_Customer;
        GO
        CREATE VIEW sales.v_open
        AS
            -- open orders only
            SELECT o.Id, c.Name FROM sales.Orders AS o JOIN dbo.Customer AS c ON c.Id = o.CustomerId WHERE o.Status = 1;
        GO
        CREATE PROCEDURE dbo.p_customers @min decimal(12,2) = 0, @count int OUTPUT
        AS
        BEGIN
            SET NOCOUNT ON;
            SELECT @count = COUNT(*) FROM dbo.Customer WHERE Credit >= @min;
        END
        GO
        CREATE FUNCTION dbo.f_double (@x int) RETURNS int AS BEGIN RETURN @x * 2; END
        GO
        CREATE FUNCTION sales.f_by_customer (@id int) RETURNS TABLE AS RETURN SELECT Id FROM sales.Orders WHERE CustomerId = @id;
        GO
        CREATE TRIGGER sales.tr_orders ON sales.Orders AFTER INSERT AS SET NOCOUNT ON;
        GO
        CREATE SYNONYM dbo.Orders FOR sales.Orders;
        GO
        """;

    [LocalDbFact]
    public async Task The_sql_server_reader_sees_the_fixed_schema_as_before()
    {
        var database = LocalDb.NewName(Guid.NewGuid().ToString("n")[..8], "Golden");
        try
        {
            LocalDb.Create(database, Schema);
            var snapshot = await new SqlServerSchemaReader { Cache = null }.ReadAsync(new SchemaSource
            {
                Id = "golden",
                Label = "Golden",
                Server = LocalDb.Server,
                Database = database,
                ConnectionString = LocalDb.Conn(database),
            }, new CompareOptions());

            Assert.False(snapshot.Failed, snapshot.Error);
            var rows = snapshot.Objects
                .OrderBy(o => o.Key, StringComparer.Ordinal)
                .Select(o => new { o.Key, o.CompareText, o.Hash })
                .ToList();
            var json = JsonSerializer.Serialize(rows, new JsonSerializerOptions { WriteIndented = true }) + "\n";
            AssertGolden("localdb-reader.json", json);
        }
        finally
        {
            LocalDb.Drop(database);
        }
    }
}
