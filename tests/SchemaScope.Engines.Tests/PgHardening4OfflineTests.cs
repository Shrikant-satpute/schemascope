    [Fact]
    public void Generated_and_identity_columns_read_as_postgres_writes_them()
    {
        var line = new ColumnInfo { Name = "line_total", Ordinal = 2, DataType = "numeric", IsComputed = true, IsPersisted = true, ComputedDefinition = "((qty)::numeric * price)" };
        var id = new ColumnInfo
        {
            Name = "id", Ordinal = 1, DataType = "bigint", IsIdentity = true, IdentityKind = "ALWAYS", IdentitySeed = "10", IdentityIncrement = "10",
            IdentityOptions = "MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 NO CYCLE",
        };
        var copy = new ColumnInfo { Name = "pid", Ordinal = 3, DataType = "bigint", IsIdentity = true, IdentityKind = "BY DEFAULT" };
        var virt = new ColumnInfo { Name = "v", Ordinal = 4, DataType = "integer", IsComputed = true, ComputedDefinition = "(a * 2)" };
        var options = new CompareOptions { IgnoreIdentitySeed = false };
        var rows = StructureDiffService.Build(Table(id, line, copy, virt), null, options)[0].Rows;
        Assert.Equal("GENERATED ALWAYS AS (((qty)::numeric * price)) STORED", rows.Single(r => r.Name == "line_total").Left!.Computed);
        Assert.Equal("GENERATED ALWAYS AS ((a * 2)) VIRTUAL", rows.Single(r => r.Name == "v").Left!.Computed);
        Assert.Equal("GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 10 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 NO CYCLE)",
            rows.Single(r => r.Name == "id").Left!.Identity);
        Assert.Equal("GENERATED BY DEFAULT AS IDENTITY", rows.Single(r => r.Name == "pid").Left!.Identity);
        Assert.DoesNotContain(rows, r => r.Left!.Computed.Contains("PERSISTED") || r.Left.Identity.Contains("(,)"));

        // SQL Server's own notation is untouched
        var sql = new DbObject { Type = DbObjectType.Table, Schema = "dbo", Name = "t" };
        sql.Columns.Add(new ColumnInfo { Name = "c", Ordinal = 1, DataType = "int", IsComputed = true, IsPersisted = true, ComputedDefinition = "([a]*(2))" });
        Assert.Equal("AS ([a]*(2)) PERSISTED", StructureDiffService.Build(sql, null, options)[0].Rows[0].Left!.Computed);
    }

    [Fact]
    public void A_key_s_fill_factor_counts_in_the_grid_only_when_fill_factor_does()
    {
        DbObject With(string definition)
        {
            var o = Table(new ColumnInfo { Name = "id", Ordinal = 1, DataType = "integer" });
            o.Indexes.Add(new IndexInfo { Name = "t_pkey", IsPrimaryKey = true, IsUnique = true, Definition = definition,
                KeyColumns = [new IndexColumnInfo { Name = "id", Ordinal = 1 }] });
            return o;
        }
        var a = With("PRIMARY KEY (id) WITH (fillfactor='80')");
        var b = With("PRIMARY KEY (id)");
        Assert.Equal("same", StructureDiffService.Build(a, b, new CompareOptions()).Single(s => s.Title == "Indexes & keys").Rows[0].Status);
        Assert.Equal("changed", StructureDiffService.Build(a, b, new CompareOptions { IgnoreFillFactor = false }).Single(s => s.Title == "Indexes & keys").Rows[0].Status);
    }

