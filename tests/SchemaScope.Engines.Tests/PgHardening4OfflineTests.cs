    // ---------------- single-object scripts change what Create scripts changes

    [Theory]
    [InlineData(DbObjectType.Sequence)]
    [InlineData(DbObjectType.Domain)]
    [InlineData(DbObjectType.EnumType)]
    [InlineData(DbObjectType.CompositeType)]
    [InlineData(DbObjectType.Schema)]
    [InlineData(DbObjectType.MaterializedView)]
    [InlineData(DbObjectType.AggregateFunction)]
    public void An_existing_object_create_scripts_changes_gets_an_object_script(DbObjectType type)
    {
        var result = new CompareResult { Targets = [new TargetSummary { Label = "t0", Engine = DatabaseEngine.PostgreSql }] };
        var row = new CompareRow { Key = "k", Type = type, Schema = "ops", Name = "x", Cells = [new TargetCell { Status = ObjectStatus.Different }] };
        Assert.Equal("alter", PgObjectScripts.Plan(result, row, 0, out var why));
        Assert.Null(why);

        // what Create scripts holds (here a range type) still says so
        row.Type = DbObjectType.RangeType;
        Assert.Equal("unavailable", PgObjectScripts.Plan(result, row, 0, out why));
        Assert.NotNull(why);
    }
