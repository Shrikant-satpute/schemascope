    protected async Task A_failing_file_is_rolled_back_says_where_without_row_values_and_nothing_after_it_runs()
    {
        var db = await pg.CreateDatabaseAsync("tgt");
        using var temp = new TempStore();
        try
        {
            await pg.ExecAsync(db, "CREATE SCHEMA app; CREATE TABLE app.d (v text); INSERT INTO app.d VALUES ('secret-row-value'), ('secret-row-value');");
            var (plan, verified) = PgPlanFiles.Plan(Path.Combine(temp.Folder, "plan"),
                ("04_columntypes", "001_kept.sql", """
                    CREATE TABLE app.kept AS SELECT current_setting('lock_timeout') AS lt,
                        current_setting('idle_in_transaction_session_timeout') AS it, current_setting('search_path') AS sp,
                        current_setting('application_name') AS an, current_setting('transaction_read_only') AS ro;

                    """),
                ("01_columns", "001_fail.sql", "CREATE TABLE app.rolled_back (id integer);\n\nALTER TABLE app.d\n    ADD CONSTRAINT d_v_key UNIQUE (v);\n"),
                ("03_missing", "001_never.sql", "CREATE TABLE app.never_run (id integer);\n"));
            var mode = new WriteMode();
            mode.Enable();

            var result = await Service(temp, mode).RunAsync(Job(db, plan, ["04_columntypes", "01_columns", "03_missing"]), verified, null);

            Assert.False(result.Success);
            Assert.Equal(2, result.Applied.Count);
            Assert.True(result.Applied[0].Ok);
            Assert.False(result.Applied[1].Ok);
            Assert.Equal("ERROR 23505 at statement 2 (line 3): could not create unique index \"d_v_key\"", result.Applied[1].Error);
            Assert.Equal("01_columns\\objects\\001_fail.sql", result.StoppedAt);
            Assert.Contains("failed and was rolled back. The 1 file(s) before it stay applied", result.Message);
            Assert.Equal(DBNull.Value, await RegClassAsync(db, "app.rolled_back"));
            Assert.Equal(DBNull.Value, await RegClassAsync(db, "app.never_run"));

            // each file ran in a transaction of its own with the apply's settings
            Assert.Equal("5s|1min|pg_catalog, pg_temp|SchemaScope|off",
                await ScalarAsync(db, "SELECT lt || '|' || it || '|' || sp || '|' || an || '|' || ro FROM app.kept"));

            var run = Assert.Single(temp.Store.GetApplyRuns());
            Assert.False(run.Success);
            Assert.Equal(2, run.Files.Count);
            Assert.DoesNotContain("secret-row-value", JsonSerializer.Serialize(run));
        }
        finally
        {
            await pg.DropAsync(db);
        }
    }

    protected async Task Statements_go_to_the_server_as_split_and_a_wrong_database_is_never_run()
    {
        var db = await pg.CreateDatabaseAsync("tgt");
        using var temp = new TempStore();
        try
        {
            await pg.ExecAsync(db, "CREATE SCHEMA app;");
            // a BEGIN ATOMIC body keeps its semicolons, and @> or ? are operators, not parameters
            var (plan, verified) = PgPlanFiles.Plan(Path.Combine(temp.Folder, "plan"),
                ("03_missing", "001_a.sql", """
                    CREATE FUNCTION app.ids() RETURNS SETOF integer LANGUAGE sql
                    BEGIN ATOMIC
                        SELECT 1;
                        SELECT 2;
                    END;
                    CREATE FUNCTION app.has(j jsonb) RETURNS boolean LANGUAGE sql AS $$ SELECT j @> '{"a":1}' AND j ? 'a' $$;
                    COMMENT ON FUNCTION app.has(jsonb) IS 'it''s @x; and $1';
                    CREATE FUNCTION app.inc(integer) RETURNS integer LANGUAGE sql RETURN $1 + 1;

                    """));
            Assert.Equal(4, Assert.Single(verified).Batches.Count);
            var mode = new WriteMode();
            mode.Enable();

            var result = await Service(temp, mode).RunAsync(Job(db, plan, ["03_missing"]), verified, null);
            Assert.True(result.Success, string.Join("\n", result.Applied.Select(a => a.Error)));
            Assert.Equal(2, await ScalarAsync(db, "SELECT app.ids()"));   // the body's last statement: both were sent
            Assert.Equal(true, await ScalarAsync(db, "SELECT app.has('{\"a\":1}')"));
            Assert.Equal(2, await ScalarAsync(db, "SELECT app.inc(1)"));   // the function's own $1, not the command's

            // the database a file runs in is the one asked for, letter for letter
            var wrong = await PgApplyExecutor.Instance.RunFileAsync(pg.ConnectionString(db), db.ToUpperInvariant(), verified[0], default, () => { });
            Assert.Equal($"The connection opened database {db}, not {db.ToUpperInvariant()}, so this file was not run.", wrong);
        }
        finally
        {
            await pg.DropAsync(db);
        }
    }

    protected async Task A_file_whose_connection_reaches_another_server_is_never_run()
    {
        var db = await pg.CreateDatabaseAsync("tgt");
        using var temp = new TempStore();
        try
        {
            await pg.ExecAsync(db, "CREATE SCHEMA app;");
            var (plan, verified) = PgPlanFiles.Plan(Path.Combine(temp.Folder, "plan"),
                ("03_missing", "001_a.sql", "CREATE TABLE app.a (id integer);\n"),
                ("03_missing", "002_b.sql", "CREATE TABLE app.b (id integer);\n"));
            var facts = await PgApplyExecutor.Instance.InspectAsync(pg.ConnectionString(db));
            Assert.NotNull(facts);
            // what a host list failing over to another cluster between files looks like: another system identifier
            var elsewhere = facts.Key.Replace("|system:", "|system:9", StringComparison.Ordinal);
            var mode = new WriteMode();
            mode.Enable();

            var refused = await Service(temp, mode).RunAsync(Job(db, plan, ["03_missing"]) with { TargetKey = elsewhere }, verified, null);
            Assert.False(refused.Success);
            Assert.Equal("The connection reached another server than the one checked before the apply, so this file was not run.",
                Assert.Single(refused.Applied).Error);
            Assert.Equal(DBNull.Value, await RegClassAsync(db, "app.a"));

            var ok = await Service(temp, mode).RunAsync(Job(db, plan, ["03_missing"]) with { TargetKey = facts.Key }, verified, null);
            Assert.True(ok.Success, string.Join("\n", ok.Applied.Select(a => a.Error)));
            Assert.Equal("app.b", await RegClassAsync(db, "app.b"));
        }
        finally
        {
            await pg.DropAsync(db);
        }
    }

    protected async Task The_target_is_known_by_its_cluster_or_for_a_deploy_login_by_its_address()
    {
        var db = await pg.CreateDatabaseAsync("tgt");
        var role = await pg.CreateRoleAsync();
        try
        {
            var asOwner = await PgApplyExecutor.Instance.InspectAsync(pg.ConnectionString(db));
            Assert.NotNull(asOwner);
            Assert.Matches($"^1\\|system:\\d+\\|5432\\|{db}$", asOwner.Key);   // the server's own port, inside the container
            Assert.Empty(asOwner.InMemory);
            Assert.Equal(asOwner.Key, PgApplyExecutor.Instance.TargetKey(asOwner, pg.Host, db));

            // a deploy login that is not a superuser reads the same identity, so both share one lock
            Assert.Equal(asOwner.Key, (await PgApplyExecutor.Instance.InspectAsync(pg.ConnectionString(db, role.Name, role.Password)))?.Key);

            // where it may not read pg_control_system() (revoked in this database), the address and port stand in
            await pg.ExecAsync(db, "REVOKE EXECUTE ON FUNCTION pg_catalog.pg_control_system() FROM PUBLIC");
            var asDeploy = await PgApplyExecutor.Instance.InspectAsync(pg.ConnectionString(db, role.Name, role.Password));
            Assert.NotNull(asDeploy);
            var address = Assert.Single(asDeploy.Hosts!);
            Assert.Equal($"1|address:{address}|5432|{db}", asDeploy.Key);

            // two spellings of one host are one target
            if (EndpointGuard.IsThisMachine(pg.Host))
            {
                var other = pg.Host == "localhost" ? "127.0.0.1" : "localhost";
                var cs = new NpgsqlConnectionStringBuilder(pg.ConnectionString(db)) { Host = other }.ConnectionString;
                Assert.Equal(asOwner.Key, (await PgApplyExecutor.Instance.InspectAsync(cs))?.Key);
            }

            // nobody to ask: no identity, and the apply refuses (the route answers 403)
            Assert.Null(await PgApplyExecutor.Instance.InspectAsync(
                new NpgsqlConnectionStringBuilder(pg.ConnectionString(db)) { Port = 1, Timeout = 2 }.ConnectionString));
            Assert.Null(await PgApplyExecutor.Instance.InspectAsync(pg.ConnectionString(db, role.Name, "wrong-password")));
        }
        finally
        {
            await pg.DropAsync(db);
            await pg.DropRoleAsync(role.Name);
        }
    }

    // ---------------- over HTTP, as the UI drives it ----------------

    private static JsonElement Body(string json) => JsonDocument.Parse(json).RootElement;

    internal static async Task<JsonElement> CompareAsync(OwnerApp o, object source, object target)
    {
        var started = await o.Post("/api/compare", new { source = new { inline = source }, targets = new[] { new { inline = target } } });
        var text = await started.Content.ReadAsStringAsync();
        Assert.True(started.StatusCode == HttpStatusCode.OK, text);
        var runId = Body(text).GetProperty("runId").GetString();
        for (var i = 0; i < 240; i++)
        {
            var run = Body(await o.Http.GetStringAsync($"/api/compare/{runId}"));
            if (run.GetProperty("status").GetString() != "running")
            {
                Assert.Equal("done", run.GetProperty("status").GetString());
                return run;
            }
            await Task.Delay(250);
        }
        throw new TimeoutException("The compare did not finish.");
    }

    internal static double MatchPercent(JsonElement run) =>
        run.GetProperty("result").GetProperty("targets")[0].GetProperty("matchPercent").GetDouble();

    private static async Task<JsonElement> ScriptsAsync(OwnerApp o, string runId, string folder)
    {
        var r = await o.Post($"/api/compare/{runId}/scripts", new
        {
            targetIndex = 0,
            options = new
            {
                outputFolder = folder,
                sections = new[] { "newColumns", "missingObjects", "columnTypes", "constraints", "indexes", "triggers", "differentModules" },
            },
        });
        var text = await r.Content.ReadAsStringAsync();
        Assert.True(r.StatusCode == HttpStatusCode.OK, text);
        var outcome = Body(text);
        Assert.True(outcome.GetProperty("success").GetBoolean(), text);
        Assert.True(outcome.GetProperty("validation").GetProperty("passed").GetBoolean(), text);
        return outcome;
    }

    private static Task<HttpResponseMessage> ApplyAsync(OwnerApp o, string runId, string planId, IEnumerable<string> sections, string confirm) =>
        o.Post($"/api/compare/{runId}/apply", new
        {
            planId, targetIndex = 0, sections, confirmDatabase = confirm, acceptDataLoss = false, progressId = Guid.NewGuid().ToString(),
        });

    private async Task<int> VersionAsync()
    {
        await using var conn = new NpgsqlConnection(pg.ConnectionString("postgres"));
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand("SELECT current_setting('server_version_num')::int", conn);
        return (int)(await cmd.ExecuteScalarAsync())!;
    }

    protected async Task Compare_scripts_apply_with_the_typed_name_and_compare_again_to_a_match()
    {
        var role = await pg.CreateRoleAsync();
        var src = await pg.CreateDatabaseAsync("src");
        var tgt = PgServer.NewName("tgt");
        await pg.ExecAsync("postgres", $"CREATE DATABASE \"{tgt}\" OWNER \"{role.Name}\"");
        await using var o = await OwnerApp.StartAsync();
        try
        {
            // the schema belongs to the deploy role on both sides (an owner that differs is a difference to review by hand)
            await pg.ExecAsync(src, PgApplyScenario.Source.Replace("CREATE SCHEMA app;", $"CREATE SCHEMA app AUTHORIZATION \"{role.Name}\";"));
            var atomic = await VersionAsync() >= 140000;
            if (atomic)
            {
                // through psql, which knows a BEGIN ATOMIC body's semicolons do not end the statement
                var (code, _, err) = await pg.ExecInContainerAsync("psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", PgServer.User, "-d", src, "-c", PgApplyScenario.SourceAtomic);
                Assert.True(code == 0, err);
            }
            // the target is the deploy role's own database, set up by that role
            await using (var conn = new NpgsqlConnection(pg.ConnectionString(tgt, role.Name, role.Password)))
            {
                await conn.OpenAsync();
                await using var cmd = new NpgsqlCommand(PgApplyScenario.Target, conn);
                await cmd.ExecuteNonQueryAsync();
            }

            await o.SetPreviewAsync(true);
            var sourceSettings = pg.Settings(src);
            var targetSettings = pg.Settings(tgt, role.Name, role.Password);
            var before = await CompareAsync(o, sourceSettings, targetSettings);
            Assert.True(MatchPercent(before) < 100);
            var runId = before.GetProperty("runId").GetString()!;

            Assert.Equal(HttpStatusCode.OK, (await o.PostJson("/api/write-mode", """{ "enabled": true, "confirm": "ENABLE" }""")).StatusCode);
            var outcome = await ScriptsAsync(o, runId, Path.Combine(o.Temp.Folder, "scripts"));
            Assert.True(outcome.GetProperty("heldBack").GetArrayLength() == 0, outcome.GetProperty("heldBack").GetRawText());
            var planId = outcome.GetProperty("planId").GetString()!;
            Assert.False(string.IsNullOrEmpty(planId), outcome.GetRawText());
            var target = outcome.GetProperty("applyTarget");
            Assert.Equal("postgreSql", target.GetProperty("engine").GetString());
            Assert.Equal(tgt, target.GetProperty("database").GetString());
            Assert.Equal($"PostgreSQL user: {role.Name}", target.GetProperty("login").GetString());
            Assert.False(target.GetProperty("protected").GetBoolean());
            var sections = outcome.GetProperty("planSections").EnumerateArray().Select(s => s.GetProperty("folder").GetString()!).ToList();
            Assert.Equal(["04_columntypes", "01_columns", "03_missing", "05_constraints", "06_indexes", "07_triggers", "10_different_modules"], sections);

            // PostgreSQL names are exact: the name in other letter case is refused, and the plan is still there
            var wrongCase = await ApplyAsync(o, runId, planId, sections, tgt.ToUpperInvariant());
            Assert.Equal(HttpStatusCode.BadRequest, wrongCase.StatusCode);
            Assert.Contains("letter case counts", await wrongCase.Content.ReadAsStringAsync());
            Assert.Empty(o.Temp.Store.GetApplyRuns());

            var applied = await ApplyAsync(o, runId, planId, sections, tgt);
            var resultText = await applied.Content.ReadAsStringAsync();
            Assert.True(applied.StatusCode == HttpStatusCode.OK, resultText);
            var result = Body(resultText);
            Assert.True(result.GetProperty("success").GetBoolean(), resultText);
            Assert.All(result.GetProperty("applied").EnumerateArray(), f => Assert.True(f.GetProperty("ok").GetBoolean()));

            // single use
            Assert.Equal(HttpStatusCode.BadRequest, (await ApplyAsync(o, runId, planId, sections, tgt)).StatusCode);

            var after = await CompareAsync(o, sourceSettings, targetSettings);
            Assert.Equal(100, MatchPercent(after));
            var rows = after.GetProperty("result").GetProperty("rows").EnumerateArray().ToList();
            Assert.All(rows, r => Assert.Equal("same", r.GetProperty("cells")[0].GetProperty("status").GetString()));
            if (atomic) Assert.Contains(rows, r => r.GetProperty("name").GetString() == "order_ids");

            var audit = Assert.Single(o.Temp.Store.GetApplyRuns());
            Assert.True(audit.Success);
            Assert.Equal(DatabaseEngine.PostgreSql, audit.Engine);
            Assert.Equal(tgt, audit.Database);
            Assert.Equal($"{pg.Host}:{pg.Port}", audit.Server);
            Assert.Equal($"PostgreSQL user: {role.Name}", audit.Login);
            Assert.Equal(result.GetProperty("applied").GetArrayLength(), audit.Files.Count);
            var history = Body(await o.Http.GetStringAsync("/api/apply-history"));
            Assert.Equal("postgreSql", history[0].GetProperty("engine").GetString());
            Assert.DoesNotContain(role.Password, JsonSerializer.Serialize(history));
        }
        finally
        {
            await pg.DropAsync(src);
            await pg.DropAsync(tgt);
            await pg.DropRoleAsync(role.Name);
        }
    }

    /// <summary>
    /// The review's reproduction: Protected saved as 127.0.0.1, the same container compared and applied as this
    /// machine's LAN address - no spelling in common and the same reported address on both. Refused by what the names
    /// resolve to (the protected connection's own answer would refuse it next). The LAN address with the container's
    /// random port is still the container this run started.
    /// </summary>
    protected async Task A_protected_server_reached_by_another_address_of_this_machine_is_refused()
    {
        if (!EndpointGuard.IsThisMachine(pg.Host) || PgApplyOfflineTests.Local() is not { } lan) return;
        var src = await pg.CreateDatabaseAsync("src");
        var tgt = await pg.CreateDatabaseAsync("tgt");
        await using var o = await OwnerApp.StartAsync();
        try
        {
            await pg.ExecAsync(src, "CREATE SCHEMA app; CREATE TABLE app.t (id integer, extra text);");
            await pg.ExecAsync(tgt, "CREATE SCHEMA app; CREATE TABLE app.t (id integer);");
            await o.SetPreviewAsync(true);
            var byLan = pg.Settings(tgt);
            byLan.Server = lan;
            var before = await CompareAsync(o, pg.Settings(src), byLan);
            var runId = before.GetProperty("runId").GetString()!;
            Assert.Equal(HttpStatusCode.OK, (await o.PostJson("/api/write-mode", """{ "enabled": true, "confirm": "ENABLE" }""")).StatusCode);
            var planId = (await ScriptsAsync(o, runId, Path.Combine(o.Temp.Folder, "scripts"))).GetProperty("planId").GetString()!;
            Assert.False(string.IsNullOrEmpty(planId));

            var guarded = pg.Settings("postgres");
            guarded.Label = "Prod";
            guarded.Server = "127.0.0.1";
            guarded.ProtectedServer = true;
            o.Temp.Store.SaveConnection(guarded);

            var r = await ApplyAsync(o, runId, planId, ["01_columns"], tgt);
            var text = await r.Content.ReadAsStringAsync();
            Assert.True(r.StatusCode == HttpStatusCode.Forbidden, text);
            Assert.StartsWith($"{tgt} is on a server marked \"Protected", Body(text).GetProperty("message").GetString());
            Assert.Empty(o.Temp.Store.GetApplyRuns());
            Assert.Equal(0L, await ScalarAsync(tgt, "SELECT count(*) FROM pg_attribute WHERE attrelid = 'app.t'::regclass AND attname = 'extra'"));
        }
        finally
        {
            await pg.DropAsync(src);
            await pg.DropAsync(tgt);
        }
    }

    protected async Task A_protected_host_is_refused_however_it_is_written()
    {
        var src = await pg.CreateDatabaseAsync("src");
        var tgt = await pg.CreateDatabaseAsync("tgt");
        await using var o = await OwnerApp.StartAsync();
        try
        {
            await pg.ExecAsync(src, "CREATE SCHEMA app; CREATE TABLE app.t (id integer, extra text);");
            await pg.ExecAsync(tgt, "CREATE SCHEMA app; CREATE TABLE app.t (id integer);");
            await o.SetPreviewAsync(true);
            var before = await CompareAsync(o, pg.Settings(src), pg.Settings(tgt));
            var runId = before.GetProperty("runId").GetString()!;
            Assert.Equal(HttpStatusCode.OK, (await o.PostJson("/api/write-mode", """{ "enabled": true, "confirm": "ENABLE" }""")).StatusCode);
            var planId = (await ScriptsAsync(o, runId, Path.Combine(o.Temp.Folder, "scripts"))).GetProperty("planId").GetString()!;
            Assert.False(string.IsNullOrEmpty(planId));

            async Task<string> RefusedWith(ConnectionSettings protectedOne)
            {
                protectedOne.ProtectedServer = true;
                var saved = o.Temp.Store.SaveConnection(protectedOne);
                try
                {
                    var r = await ApplyAsync(o, runId, planId, ["01_columns"], tgt);
                    var text = await r.Content.ReadAsStringAsync();
                    Assert.True(r.StatusCode == HttpStatusCode.Forbidden, text);
                    return Body(text).GetProperty("message").GetString()!;
                }
                finally
                {
                    o.Temp.Store.DeleteConnection(saved.Id);
                }
            }

            // a protected connection protects every engine and port on its host: the default port, another engine
            if (EndpointGuard.IsThisMachine(pg.Host))
            {
                Assert.Contains("Protected", await RefusedWith(new ConnectionSettings
                    { Engine = DatabaseEngine.PostgreSql, Server = "localhost:5432", Database = "prod" }));
                Assert.Contains("Protected", await RefusedWith(new ConnectionSettings
                    { Engine = DatabaseEngine.PostgreSql, Server = "localhost", Port = 5432, Database = "prod" }));
            }
            var sqlHost = EndpointGuard.IsThisMachine(pg.Host) ? $"{Environment.MachineName}\\PROD" : pg.Host;
            Assert.Contains("Protected", await RefusedWith(new ConnectionSettings { Server = sqlHost, Database = "prod" }));
            // a host list is protected if any host is; a string that cannot be read protects everything
            Assert.Contains("Protected", await RefusedWith(new ConnectionSettings
                { Engine = DatabaseEngine.PostgreSql, UseRawConnectionString = true, RawConnectionString = $"Host=prod.example.invalid,{pg.Host};Database=prod" }));
            Assert.Contains("Protected", await RefusedWith(new ConnectionSettings
                { Engine = DatabaseEngine.PostgreSql, UseRawConnectionString = true, RawConnectionString = "Host=prod:1;Port=2;Database=prod" }));

            // the address the server reports for itself is checked too, however the connection spells the host
            var reported = (string?)await ScalarAsync(tgt, "SELECT host(inet_server_addr())");
            Assert.NotNull(reported);
            var byAddress = await RefusedWith(new ConnectionSettings { Engine = DatabaseEngine.PostgreSql, Server = reported, Database = "prod" });
            if (!HostNames.Same(reported, pg.Host)) Assert.Contains("is on a server marked", byAddress);

            // nothing was applied or logged, and with nothing protected the same plan runs
            Assert.Empty(o.Temp.Store.GetApplyRuns());
            Assert.Equal(0L, await ScalarAsync(tgt, "SELECT count(*) FROM pg_attribute WHERE attrelid = 'app.t'::regclass AND attname = 'extra'"));
            var ok = await ApplyAsync(o, runId, planId, ["01_columns"], tgt);
            Assert.True(ok.StatusCode == HttpStatusCode.OK, await ok.Content.ReadAsStringAsync());
            Assert.True(Body(await ok.Content.ReadAsStringAsync()).GetProperty("success").GetBoolean());
        }
        finally
        {
            await pg.DropAsync(src);
            await pg.DropAsync(tgt);
        }
    }
}

