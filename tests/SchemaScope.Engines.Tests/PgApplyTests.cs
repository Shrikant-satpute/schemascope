/// <summary>
/// PostgreSQL Write mode on real servers: the apply's safety stops (ported from the LocalDB ApplySafety and
/// ApplyIntegration tests), its identity, and the full flow over HTTP - compare, scripts, apply with the typed name,
/// compare again to 100% - with the Protected refusals in front of it. Throwaway databases on the test container only.
/// </summary>
public abstract class PgApplyTestsBase(PgServer pg)
{
    private static readonly TimeSpan Ended = TimeSpan.FromSeconds(4);

    private static ApplyService Service(TempStore temp, WriteMode mode) =>
        new(temp.Store, mode, NullLogger<ApplyService>.Instance, [PgApplyExecutor.Instance]);

    private ApplyJob Job(string db, List<PlanFile> plan, IReadOnlyList<string> sections, string? progressId = null) =>
        new("run", pg.ConnectionString(db), new ApplyTarget
        {
            Label = "Throwaway", Engine = DatabaseEngine.PostgreSql, Server = pg.Host, Port = pg.Port, Database = db,
            Login = "PostgreSQL user: postgres",
        }, plan, sections, progressId);

    private async Task<object?> ScalarAsync(string db, string sql)
    {
        await using var conn = new NpgsqlConnection(pg.ConnectionString(db));
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        return await cmd.ExecuteScalarAsync();
    }

    private Task<object?> RegClassAsync(string db, string name) => ScalarAsync(db, $"SELECT to_regclass('{name}')::text");

    /// <summary>Another session holding ACCESS SHARE on app.t until it is disposed: an ALTER TABLE on it waits.</summary>
    private async Task<(NpgsqlConnection Conn, NpgsqlTransaction Tx)> HoldAsync(string db)
    {
        var holder = new NpgsqlConnection(pg.ConnectionString(db));
        await holder.OpenAsync();
        var tx = await holder.BeginTransactionAsync();
        await using var cmd = new NpgsqlCommand("SELECT count(*) FROM app.t", holder, tx);
        await cmd.ExecuteScalarAsync();
        return (holder, tx);
    }

    private async Task<ApplyResult> BlockedAsync(string db, TempStore temp, string root, Action<ApplyService, WriteMode, string> end)
    {
        var (plan, verified) = PgPlanFiles.Plan(root,
            ("04_columntypes", "001_a.sql", "ALTER TABLE app.t ADD COLUMN c integer;\n"),
            ("03_missing", "001_b.sql", "CREATE TABLE app.b (id integer);\n"));
        var mode = new WriteMode();
        mode.Enable();
        var service = Service(temp, mode);
        var progressId = Guid.NewGuid().ToString();

        var (holder, tx) = await HoldAsync(db);
        ApplyResult result;
        await using (holder)
        {
            var started = DateTime.UtcNow;
            var run = service.RunAsync(Job(db, plan, ["04_columntypes", "03_missing"], progressId), verified, null);
            await Task.Delay(1500);
            Assert.False(run.IsCompleted);   // waiting on the lock

            end(service, mode, progressId);
            var finished = await Task.WhenAny(run, Task.Delay(TimeSpan.FromSeconds(20)));
            Assert.Same(run, finished);
            result = await run;
            // ended by the stop, well before the 5 s lock_timeout would have ended it
            Assert.True(DateTime.UtcNow - started < Ended, $"took {DateTime.UtcNow - started}");

            await tx.RollbackAsync();
        }
        await Task.Delay(300);
        Assert.Equal(0L, await ScalarAsync(db, "SELECT count(*) FROM pg_attribute WHERE attrelid = 'app.t'::regclass AND attname = 'c'"));
        Assert.Equal(DBNull.Value, await RegClassAsync(db, "app.b"));   // rolled back, never committed later
        return result;
    }

    protected async Task Cancel_now_ends_a_file_stuck_on_a_lock_and_rolls_it_back()
    {
        var db = await pg.CreateDatabaseAsync("tgt");
        using var temp = new TempStore();
        var root = Path.Combine(temp.Folder, "plan");
        try
        {
            await pg.ExecAsync(db, "CREATE SCHEMA app; CREATE TABLE app.t (id integer); INSERT INTO app.t VALUES (1);");

            var result = await BlockedAsync(db, temp, root, (service, _, id) => Assert.True(service.Stop(id, now: true)));

            Assert.False(result.Success);
            var file = Assert.Single(result.Applied);
            Assert.False(file.Ok);
            Assert.Equal("Cancelled while it ran: this file was rolled back.", file.Error);
            Assert.Contains("Stopped because you cancelled it", result.Message);
            Assert.Contains("04_columntypes\\objects\\001_a.sql was rolled back and 1 were not run", result.Message);
            var audit = Assert.Single(temp.Store.GetApplyRuns());
            Assert.Equal(result.Message, audit.Message);
            Assert.Equal(DatabaseEngine.PostgreSql, audit.Engine);
            Assert.Equal($"{pg.Host}:{pg.Port}", audit.Server);
        }
        finally
        {
            await pg.DropAsync(db);
        }
    }

