    [Fact]
    public void A_key_s_fill_factor_is_left_out_of_the_compare_when_ignored()
    {
        Assert.Equal("PRIMARY KEY (id)", PgCanonicalWriter.KeyText("PRIMARY KEY (id) WITH (fillfactor='80')", ignoreFillFactor: true));
        Assert.Equal("UNIQUE (c) WITH (deduplicate_items='off')", PgCanonicalWriter.KeyText("UNIQUE (c) WITH (fillfactor='80', deduplicate_items='off')", true));
        Assert.Equal("EXCLUDE USING gist (a WITH =) WHERE ((b > 0))", PgCanonicalWriter.KeyText("EXCLUDE USING gist (a WITH =) WITH (fillfactor='70') WHERE ((b > 0))", true));
        Assert.Equal("PRIMARY KEY (id) WITH (fillfactor='80')", PgCanonicalWriter.KeyText("PRIMARY KEY (id) WITH (fillfactor='80')", ignoreFillFactor: false));
        Assert.Equal(new Dictionary<string, string> { ["fillfactor"] = "80" }, PgCanonicalWriter.KeyOptions("PRIMARY KEY (id) WITH (fillfactor='80') DEFERRABLE"));
        Assert.Equal("PRIMARY KEY (id) DEFERRABLE", PgCanonicalWriter.WithoutKeyOptions("PRIMARY KEY (id) WITH (fillfactor='80') DEFERRABLE"));
    }

    // ---------------- the new kinds as PostgreSQL writes them

    [Fact]
    public void Text_search_operator_classes_and_casts_are_written_as_their_create_statements()
    {
        var dict = new DbObject { Type = DbObjectType.TextSearchDictionary, Schema = "ts", Name = "d", Fold = IdentifierFold.Exact };
        dict.Properties["template"] = "simple";
        dict.Properties["options"] = "stopwords = 'english'";
        Assert.Equal("CREATE TEXT SEARCH DICTIONARY \"ts\".\"d\" (TEMPLATE = simple, stopwords = 'english');", PgCanonicalWriter.Write(dict, new CompareOptions()));

        var cfg = new DbObject { Type = DbObjectType.TextSearchConfiguration, Schema = "ts", Name = "cfg", Fold = IdentifierFold.Exact };
        cfg.Properties["parser"] = "\"default\"";
        cfg.Properties[PgCanonicalWriter.MappingPrefix + "word"] = "english_stem";
        cfg.Properties[PgCanonicalWriter.MappingPrefix + "asciiword"] = "ts.d, english_stem";
        Assert.Equal("CREATE TEXT SEARCH CONFIGURATION \"ts\".\"cfg\" (PARSER = \"default\");\n" +
                     "ALTER TEXT SEARCH CONFIGURATION \"ts\".\"cfg\" ADD MAPPING FOR asciiword WITH ts.d, english_stem;\n" +
                     "ALTER TEXT SEARCH CONFIGURATION \"ts\".\"cfg\" ADD MAPPING FOR word WITH english_stem;", PgCanonicalWriter.Write(cfg, new CompareOptions()));

        var oc = new DbObject { Type = DbObjectType.OperatorClass, Schema = "oc", Name = "rev_ops", Signature = "btree", Fold = IdentifierFold.Exact };
        oc.Properties["type"] = "integer";
        oc.Properties["method"] = "btree";
        oc.Properties["items"] = "OPERATOR 1 >(integer,integer)\nFUNCTION 1 (integer, integer) oc.cmp(integer,integer)";
        Assert.Equal("CREATE OPERATOR CLASS \"oc\".\"rev_ops\" FOR TYPE integer USING \"btree\" AS\n    OPERATOR 1 >(integer,integer),\n" +
                     "    FUNCTION 1 (integer, integer) oc.cmp(integer,integer);", PgCanonicalWriter.Write(oc, new CompareOptions()));

        var cast = new DbObject { Type = DbObjectType.Cast, Schema = "uc", Name = "numeric AS uc.money2", Fold = IdentifierFold.Exact };
        cast.Properties["source"] = "numeric";
        cast.Properties["target"] = "uc.money2";
        cast.Properties["method"] = "FUNCTION";
        cast.Properties["function"] = "uc.to_m(numeric)";
        cast.Properties["context"] = "ASSIGNMENT";
        Assert.Equal("CREATE CAST (numeric AS uc.money2) WITH FUNCTION uc.to_m(numeric) AS ASSIGNMENT;", PgCanonicalWriter.Write(cast, new CompareOptions()));
    }

    // ---------------- excluded schemas: the user's own guest is the user's

    [Fact]
    public void A_typed_list_of_excluded_schemas_is_the_user_s_every_name_of_it()
    {
        var typed = new CompareOptions { ExcludedSchemas = ["guest", "tmp"] }.ForEngine(new PgDialect().DefaultExcludedSchemas, exactNames: true);
        Assert.True(typed.IsExcluded(DbObjectType.Table, "guest", "scratch"));
        Assert.True(typed.IsExcluded(DbObjectType.Table, "tmp", "scratch2"));
        Assert.True(typed.IsExcluded(DbObjectType.Table, "pg_catalog", "t"));
        Assert.False(typed.IsExcluded(DbObjectType.Table, "sys", "t"));

        // the defaults as the app writes them still give way to PostgreSQL's own
        var defaults = new CompareOptions();
        defaults.ExcludedSchemas.Add("tmp");
        var pg = defaults.ForEngine(new PgDialect().DefaultExcludedSchemas, exactNames: true);
        Assert.False(pg.IsExcluded(DbObjectType.Table, "guest", "scratch"));
        Assert.True(pg.IsExcluded(DbObjectType.Table, "tmp", "scratch2"));
    }

