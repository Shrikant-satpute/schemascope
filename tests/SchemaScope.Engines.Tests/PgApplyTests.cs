    protected async Task A_lock_wait_gives_up_after_the_lock_timeout_and_rolls_the_file_back()
    {
        var db = await pg.CreateDatabaseAsync("tgt");
        using var temp = new TempStore();
        try
        {
            await pg.ExecAsync(db, "CREATE SCHEMA app; CREATE TABLE app.t (id integer);");
            var (plan, verified) = PgPlanFiles.Plan(Path.Combine(temp.Folder, "plan"),
                ("04_columntypes", "001_a.sql", "CREATE TABLE app.first (id integer);\n\nALTER TABLE app.t\n    ADD COLUMN c integer;\n"));
            var mode = new WriteMode();
            mode.Enable();

            var (holder, tx) = await HoldAsync(db);
            ApplyResult result;
            await using (holder)
            {
                result = await Service(temp, mode).RunAsync(Job(db, plan, ["04_columntypes"]), verified, null);
                await tx.RollbackAsync();
            }

            Assert.False(result.Success);
            Assert.Equal("ERROR 55P03 at statement 2 (line 3): canceling statement due to lock timeout", Assert.Single(result.Applied).Error);
            Assert.Contains("failed and was rolled back", result.Message);
            Assert.Equal(DBNull.Value, await RegClassAsync(db, "app.first"));
        }
        finally
        {
            await pg.DropAsync(db);
        }
    }

