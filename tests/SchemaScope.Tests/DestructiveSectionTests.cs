/// <summary>11_destructive with in-memory catalogs: every probe fails at once (refused port), so only what needs no probe is written.</summary>
public class DestructiveSectionTests
{
    private static readonly ObjectName A = new("dbo", "A");

    /// <summary>Every file of a run (path + text) as one SHA-256, with what changes from run to run or machine to machine blanked.</summary>
    private static string Digest(string root)
    {
        var sb = new StringBuilder();
        foreach (var f in Directory.GetFiles(root, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
        {
            var rel = Path.GetRelativePath(root, f).Replace('\\', '/');
            var text = File.ReadAllText(f);
            // the date, and the "not checked" warnings, whose order follows parallel probes
            if (rel == "README.md")
                text = string.Join("\n", text.Split('\n').Where(l =>
                    !l.StartsWith("Generated by SchemaScope on ", StringComparison.Ordinal) && !l.Contains(" not checked (", StringComparison.Ordinal)));
            // a refused probe's message depends on the machine (network error text, language)
            text = Regex.Replace(text, @"(Msg -?\d+: |timed out).*", "PROBE FAILED");
            sb.Append(rel).Append('\0').Append(text).Append('\0');
        }
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString())));
    }

    [Fact]
    public async Task With_the_option_off_the_output_is_byte_identical_to_before_it_existed()
    {
        // digests of the same two runs made with the generator as it was before IncludeDestructive (release-1.2, 926834a)
        using var whole = new TempFolder();
        var o = ObjectFixture.Options(whole.Path);
        o.OnlyObjects = null;
        Assert.False(o.IncludeDestructive);
        var outcome = await ObjectFixture.Generator().GenerateAsync(ObjectFixture.Source, ObjectFixture.Target, o, new HashSet<string>(), default,
            differentCandidates: new Dictionary<string, LineChange> { ["dbo.p_diff"] = new(1, 1) });
        Assert.True(outcome.Success, outcome.Message);
        Assert.Equal("768F7256079238943279B081A3507E927847E3AE8EF6CB830A6BDB4A77A3E89C", Digest(outcome.Path!));

        using var scoped = new TempFolder();
        var one = await ObjectFixture.Generator().GenerateAsync(ObjectFixture.Source, ObjectFixture.Target,
            ObjectFixture.Options(scoped.Path, A), new HashSet<string>(), default);
        Assert.Equal("1B16E76C6CD17AB832BE175B210447DEF82AFC62B64375587E398561605F78C9", Digest(one.Path!));
    }

    private static ColumnRow Col(string tbl, int id, string col, string dt = "int", int len = 4, bool nullable = true) =>
        new("dbo", tbl, id, col, dt, len, 10, 0, nullable, false, false, null, null, false, null, null, false);

    /// <summary>dbo.A on both sides; the target adds a check, an index, a column, a table and a procedure, and a same-name check with another rule.</summary>
    private static (ScriptSchema Src, ScriptSchema Tgt) Pair()
    {
        var src = ScriptSchema.FromRows("src", ObjectFixture.Coll, [],
            [A],
            [Col("A", 1, "a_id", nullable: false), Col("A", 2, "a_code", "varchar", 10)],
            [],
            [new CheckRow("dbo", "A", "CK_A_same", "([a_id]>(0))", false, false, false)],
            [new KeyRow("dbo", "A", "PK_A", "PK", false, "CLUSTERED", "[a_id] ASC")],
            [], [], [], [], [], []);
        var tgt = ScriptSchema.FromRows("tgt", ObjectFixture.Coll,
            [ObjectFixture.Mod("p_extra", "P", "CREATE PROCEDURE dbo.p_extra AS SELECT 1")],
            [A, new("dbo", "X")],
            [Col("A", 1, "a_id", nullable: false), Col("A", 2, "a_code", "varchar", 50), Col("A", 3, "a_extra"), Col("X", 1, "x_id")],
            [],
            [
                new CheckRow("dbo", "A", "CK_A_same", "([a_id]>(1))", false, false, false),
                new CheckRow("dbo", "A", "CK_A_extra", "([a_id]<(100))", false, false, false),
            ],
            [new KeyRow("dbo", "A", "PK_A", "PK", false, "CLUSTERED", "[a_id] ASC")],
            [],
            [new IndexRow("dbo", "A", "IX_A_extra", "NONCLUSTERED", false, null, "[a_code] ASC", null)],
            [], [], [], []);
        return (src, tgt);
    }

    private static Task<ScriptOutcome> Run(string folder, bool destructive, params ObjectName[] only)
    {
        var (src, tgt) = Pair();
        var o = ObjectFixture.Options(folder, only);
        if (only.Length == 0) o.OnlyObjects = null;
        o.IncludeDestructive = destructive;
        return ObjectFixture.Generator(src, tgt).GenerateAsync(ObjectFixture.Source, ObjectFixture.Target, o, new HashSet<string>(), default);
    }

    [Fact]
    public async Task Off_writes_no_11_and_no_destructive_review()
    {
        using var temp = new TempFolder();
        var outcome = await Run(temp.Path, destructive: false);
        Assert.True(outcome.Success, outcome.Message);
        Assert.DoesNotContain(outcome.Folders, f => f.Folder == DestructiveGenerator.Folder);
        Assert.DoesNotContain(outcome.Files, f => f.Folder == DestructiveGenerator.Folder || f.RelativePath == ReviewLog.NotAppliedDestructive);
        Assert.DoesNotContain("11_destructive", File.ReadAllText(Path.Combine(outcome.Path!, "README.md")));
    }

    [Fact]
    public async Task On_drops_what_needs_no_probe_and_holds_whatever_a_failed_probe_could_not_prove()
    {
        using var temp = new TempFolder();
        var outcome = await Run(temp.Path, destructive: true);
        Assert.True(outcome.Success, outcome.Message);
        Assert.True(outcome.Validation.Passed, string.Join("; ", outcome.Validation.Problems));

        var folder = Assert.Single(outcome.Folders, f => f.Folder == DestructiveGenerator.Folder);
        Assert.False(folder.InRunAll);
        Assert.Equal(DestructiveGenerator.Title, folder.Title);
        var files = outcome.Files.Where(f => f.Folder == DestructiveGenerator.Folder && f.IsObjectFile).Select(f => f.RelativePath).ToList();
        Assert.Equal([@"objects\001_drop_check_A_CK_A_extra.sql", @"objects\002_drop_index_A_IX_A_extra.sql"], files);
        var check = ScriptWriter.ReadBack(Path.Combine(outcome.Path!, DestructiveGenerator.Folder, files[0]));
        Assert.StartsWith(ScriptText.HdrTbl + "-- 11_destructive: CAN LOSE DATA.", check);
        Assert.EndsWith("ALTER TABLE [dbo].[A] DROP CONSTRAINT [CK_A_extra]\r\nGO\r\n", check);

        // never part of RUN.ps1; the README warns in red
        Assert.DoesNotContain("11_", File.ReadAllText(Path.Combine(outcome.Path!, "RUN.ps1")));
        var readme = File.ReadAllText(Path.Combine(outcome.Path!, "README.md"));
        Assert.Contains("> [!CAUTION]", readme);
        Assert.Contains("| 11_destructive | **CAN LOSE DATA.**", readme);

        // everything a probe was needed for is held, with the reason, in its own review file
        var held = outcome.HeldBack.Where(h => h.Section == DestructiveGenerator.Folder).ToList();
        Assert.Contains(held, h => h.Object == "dbo.p_extra" && h.Reason.Contains("could not read what uses"));
        Assert.Contains(held, h => h.Object == "dbo.X" && h.Reason.Contains("could not"));
        Assert.Contains(held, h => h.Object == "A.a_extra" && h.Reason.Contains("could not"));
        Assert.Contains(held, h => h.Object == "A.a_code" && h.Reason.Contains("could not"));   // varchar(50) -> varchar(10)
        Assert.Contains(held, h => h.Object == "A.CK_A_same" && h.Reason.Contains("could not be checked"));
        var review = File.ReadAllText(Path.Combine(outcome.Path!, ReviewLog.Folder, ReviewLog.NotAppliedDestructive));
        Assert.Contains("p_extra", review);

        // target_only_objects.md says which ones 11 drops - none here, everything was held
        var targetOnly = File.ReadAllText(Path.Combine(outcome.Path!, ReviewLog.Folder, ReviewReports.TargetOnlyFile));
        Assert.DoesNotContain("11_destructive drops it", targetOnly);
    }

    [Fact]
    public async Task A_scoped_run_keeps_11_to_its_own_object()
    {
        using var temp = new TempFolder();
        var outcome = await Run(temp.Path, destructive: true, new ObjectName("dbo", "p_extra"));
        Assert.True(outcome.Success, outcome.Message);
        var held = Assert.Single(outcome.HeldBack);
        Assert.Equal("dbo.p_extra", held.Object);
        foreach (var f in outcome.Files.Where(f => f.Kind is not WrittenFileKind.Runner && f.RelativePath != ScriptValidator.ReportFile))
        {
            var text = File.ReadAllText(f.FullPath);
            foreach (var other in new[] { "CK_A_extra", "IX_A_extra", "a_extra", "CK_A_same", "a_code", "[X]", "dbo.X" })
                Assert.DoesNotContain(other, text);
        }
    }
}

/// <summary>Throwaway LocalDB databases. Nothing here ever connects anywhere but (localdb)\MSSQLLocalDB.</summary>
internal static class DestructiveDb
{
    private const string Server = @"(localdb)\MSSQLLocalDB";

    public static string Cs(string database) =>
        $"Data Source={Server};Initial Catalog={database};Integrated Security=true;TrustServerCertificate=true;Connect Timeout=60";

    /// <summary>Runs a script's GO batches in order (the way sqlcmd does), on one connection.</summary>
    public static void Run(string database, string script)
    {
        using var c = new SqlConnection(Cs(database));
        c.Open();
        foreach (var b in ScriptText.SplitBatches(script))
        {
            using var cmd = new SqlCommand(b.Text, c) { CommandTimeout = 120 };
            cmd.ExecuteNonQuery();
        }
    }

    public static object? Scalar(string database, string sql)
    {
        using var c = new SqlConnection(Cs(database));
        c.Open();
        using var cmd = new SqlCommand(sql, c);
        var v = cmd.ExecuteScalar();
        return v is DBNull ? null : v;
    }

    public static void Create(string database) => Run("master", $"CREATE DATABASE {Ddl.Bracket(database)}");

    public static void Drop(string database)
    {
        SqlConnection.ClearAllPools();
        Run("master", $"IF DB_ID({ScriptText.Lit(database)}) IS NOT NULL BEGIN " +
                      $"ALTER DATABASE {Ddl.Bracket(database)} SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE {Ddl.Bracket(database)}; END");
    }
}

/// <summary>
/// 11_destructive against two real (throwaway) LocalDB databases: what it writes, what it holds and why, and that the
/// files run and leave the target as the source is. Skipped where LocalDB is not installed.
/// </summary>
public class DestructiveLocalDbTests
{
    private const string SourceDdl = """
        CREATE TABLE dbo.Parent (id int NOT NULL CONSTRAINT PK_Parent PRIMARY KEY, code varchar(10) NOT NULL, amount decimal(10,2) NULL,
            status varchar(20) NOT NULL CONSTRAINT CK_Parent_status CHECK (status IN ('A','B','C')), note varchar(30) NOT NULL);
        CREATE TABLE dbo.Child (id int NOT NULL CONSTRAINT PK_Child PRIMARY KEY, parent_id int NULL CONSTRAINT FK_Child_Parent REFERENCES dbo.Parent(id), qty int NOT NULL);
        CREATE INDEX IX_Child_qty ON dbo.Child(qty);
        GO
        CREATE PROCEDURE dbo.p_common AS SELECT id FROM dbo.Parent;
        """;

    private const string TargetDdl = """
        CREATE TABLE dbo.Parent (id int NOT NULL CONSTRAINT PK_Parent PRIMARY KEY, code varchar(50) NOT NULL, amount decimal(10,4) NULL,
            status varchar(20) NOT NULL CONSTRAINT CK_Parent_status CHECK (status IN ('A','B')),
            extra_col nvarchar(100) NULL CONSTRAINT DF_Parent_extra DEFAULT N'x', note varchar(20) NULL);
        CREATE TABLE dbo.Child (id int NOT NULL CONSTRAINT PK_Child PRIMARY KEY, parent_id int NULL CONSTRAINT FK_Child_Parent REFERENCES dbo.Parent(id), qty int NULL,
            CONSTRAINT UQ_Child_parent UNIQUE (parent_id, id), CONSTRAINT CK_Child_qty CHECK (qty >= 0));
        CREATE INDEX IX_Child_qty ON dbo.Child(qty);
        CREATE TABLE dbo.Extra (id int NOT NULL CONSTRAINT PK_Extra PRIMARY KEY, v int NULL);
        CREATE TABLE dbo.ExtraChild (id int NOT NULL CONSTRAINT PK_ExtraChild PRIMARY KEY, extra_id int NULL CONSTRAINT FK_ExtraChild_Extra REFERENCES dbo.Extra(id));
        CREATE TABLE dbo.Kept (id int NOT NULL CONSTRAINT PK_Kept PRIMARY KEY);
        CREATE TYPE dbo.TT_extra AS TABLE (id int NOT NULL);
        CREATE SEQUENCE dbo.seq_extra AS int START WITH 1;
        CREATE SYNONYM dbo.syn_extra FOR dbo.Parent;
        INSERT dbo.Parent (id, code, amount, status, note) VALUES (1, 'short', 1.2345, 'A', 'n1'), (2, 'also', 2.5, 'B', 'n2');
        INSERT dbo.Child VALUES (1, 1, 5), (2, 2, 7);
        INSERT dbo.Extra VALUES (1, 10), (2, 20), (3, 30);
        INSERT dbo.ExtraChild VALUES (1, 1);
        GO
        CREATE FUNCTION dbo.f_extra() RETURNS int AS BEGIN RETURN 1 END;
        GO
        CREATE VIEW dbo.v_extra WITH SCHEMABINDING AS SELECT id, v FROM dbo.Extra;
        GO
        CREATE PROCEDURE dbo.p_extra @rows dbo.TT_extra READONLY AS SELECT dbo.f_extra(), v FROM dbo.Extra;
        GO
        CREATE PROCEDURE dbo.p_common AS SELECT id FROM dbo.Parent UNION ALL SELECT id FROM dbo.Kept;
        GO
        CREATE TRIGGER dbo.tr_parent ON dbo.Parent AFTER INSERT AS SET NOCOUNT ON;
        """;

    private sealed class Pair : IDisposable
    {
        public string Src { get; } = $"SchemaScope_Test_{Guid.NewGuid():n}"[..29] + "_Src";
        public string Tgt { get; }

        public Pair()
        {
            Tgt = Src[..^4] + "_Tgt";
            try
            {
                DestructiveDb.Create(Src);
                DestructiveDb.Create(Tgt);
                DestructiveDb.Run(Src, SourceDdl);
                DestructiveDb.Run(Tgt, TargetDdl);
            }
            catch
            {
                Dispose();
                throw;
            }
        }

        public ScriptEndpoint Source => new("Src", @"(localdb)\MSSQLLocalDB", Src, DestructiveDb.Cs(Src));
        public ScriptEndpoint Target => new("Tgt", @"(localdb)\MSSQLLocalDB", Tgt, DestructiveDb.Cs(Tgt));

        public void Dispose()
        {
            DestructiveDb.Drop(Src);
            DestructiveDb.Drop(Tgt);
        }
    }

    private static Task<ScriptOutcome> Generate(Pair db, string folder, params ObjectName[] only) =>
        new ScriptGenerator().GenerateAsync(db.Source, db.Target, new ScriptOptions
        {
            OutputFolder = folder,
            IncludeDestructive = true,
            OnlyObjects = only.Length == 0 ? null : [.. only],
            RunFolderName = "run",
        }, new HashSet<string>(), default);

    [LocalDbFact]
    public async Task Drops_extras_in_dependency_order_holds_what_would_break_and_the_files_run()
    {
        using var db = new Pair();
        using var temp = new TempFolder();
        var outcome = await Generate(db, temp.Path);
        Assert.True(outcome.Success, outcome.Message);
        Assert.True(outcome.Validation.Passed, string.Join("; ", outcome.Validation.Problems));

        var files = outcome.Files.Where(f => f.Folder == DestructiveGenerator.Folder && f.IsObjectFile)
            .Select(f => f.RelativePath[(f.RelativePath.IndexOf('_') + 1)..^4]).ToList();   // "drop_table_Extra"
        int At(string name) { var i = files.IndexOf(name); Assert.True(i >= 0, $"{name} not in [{string.Join(", ", files)}]"); return i; }

        // column changes: narrowing that fits, NULL -> NOT NULL around an index; the scale change that would round is held
        At("alter_column_Parent_code");
        var qty = ScriptWriter.ReadBack(outcome.Files.Single(f => f.RelativePath.EndsWith("alter_column_Child_qty.sql")).FullPath);
        Assert.Contains("DROP INDEX [IX_Child_qty] ON [dbo].[Child]", qty);
        Assert.Contains("ALTER COLUMN [qty] [int] NOT NULL", qty);
        Assert.Contains(outcome.HeldBack, h => h.Object == "Parent.amount" && h.Reason.Contains("1 row(s)"));
        // 04 widens varchar(20) to varchar(30); NOT NULL comes from 11, to the source's type, so it never narrows 04's work back
        Assert.EndsWith("ALTER TABLE [dbo].[Parent] ALTER COLUMN [note] [varchar](30) NOT NULL\r\nGO\r\n",
            ScriptWriter.ReadBack(outcome.Files.Single(f => f.RelativePath.EndsWith("alter_column_Parent_note.sql")).FullPath));

        // dependents first: the schema-bound view and the child table before Extra, the procedure before its type and function
        Assert.True(At("drop_view_v_extra") < At("drop_table_Extra"));
        Assert.True(At("drop_table_ExtraChild") < At("drop_table_Extra"));
        Assert.True(At("drop_procedure_p_extra") < At("drop_table_type_TT_extra"));
        Assert.True(At("drop_procedure_p_extra") < At("drop_function_f_extra"));
        Assert.True(At("drop_trigger_tr_parent") < At("drop_column_Parent_extra_col"));
        foreach (var f in new[] { "replace_check_Parent_CK_Parent_status", "drop_check_Child_CK_Child_qty", "drop_unique_Child_UQ_Child_parent",
                                  "drop_synonym_syn_extra", "drop_sequence_seq_extra" })
            At(f);
        // a table code that stays reads is held, never dropped
        Assert.Contains(outcome.HeldBack, h => h.Object == "dbo.Kept" && h.Reason.Contains("dbo.p_common uses it"));
        Assert.DoesNotContain(files, f => f.Contains("Kept"));
        var extra = ScriptWriter.ReadBack(outcome.Files.Single(f => f.RelativePath.EndsWith("drop_table_Extra.sql")).FullPath);
        Assert.Contains("and its 3 row(s)", extra);
        Assert.Contains(outcome.Files, f => f.RelativePath == @"rollback\_ALL.sql" && f.Folder == DestructiveGenerator.Folder);

        // run 11 on the throwaway target, file by file, as run_all.ps1 would
        foreach (var f in outcome.Files.Where(f => f.Folder == DestructiveGenerator.Folder && f.IsObjectFile).OrderBy(f => f.RelativePath, StringComparer.Ordinal))
            DestructiveDb.Run(db.Tgt, ScriptWriter.ReadBack(f.FullPath));

        Assert.Null(DestructiveDb.Scalar(db.Tgt, "SELECT OBJECT_ID('dbo.Extra')"));
        Assert.Null(DestructiveDb.Scalar(db.Tgt, "SELECT OBJECT_ID('dbo.p_extra')"));
        Assert.Null(DestructiveDb.Scalar(db.Tgt, "SELECT TYPE_ID('dbo.TT_extra')"));
        Assert.Null(DestructiveDb.Scalar(db.Tgt, "SELECT COL_LENGTH('dbo.Parent', 'extra_col')"));
        Assert.NotNull(DestructiveDb.Scalar(db.Tgt, "SELECT OBJECT_ID('dbo.Kept')"));
        Assert.Equal((short)10, DestructiveDb.Scalar(db.Tgt, "SELECT max_length FROM sys.columns WHERE object_id = OBJECT_ID('dbo.Parent') AND name = 'code'"));
        Assert.Equal(false, DestructiveDb.Scalar(db.Tgt, "SELECT is_nullable FROM sys.columns WHERE object_id = OBJECT_ID('dbo.Child') AND name = 'qty'"));
        Assert.NotNull(DestructiveDb.Scalar(db.Tgt, "SELECT 1 FROM sys.indexes WHERE name = 'IX_Child_qty'"));
        Assert.Contains("'C'", (string)DestructiveDb.Scalar(db.Tgt, "SELECT definition FROM sys.check_constraints WHERE name = 'CK_Parent_status'")!);
        Assert.Equal(2, DestructiveDb.Scalar(db.Tgt, "SELECT COUNT(*) FROM dbo.Parent"));

        // a dropped module comes back from its rollback file
        DestructiveDb.Run(db.Tgt, ScriptWriter.ReadBack(outcome.Files.Single(f => f.IsRollback && f.RelativePath.EndsWith("drop_trigger_tr_parent.sql")).FullPath));
        Assert.NotNull(DestructiveDb.Scalar(db.Tgt, "SELECT OBJECT_ID('dbo.tr_parent')"));
    }

    [LocalDbFact]
    public async Task A_scoped_run_for_an_extra_procedure_writes_only_its_drop()
    {
        using var db = new Pair();
        using var temp = new TempFolder();
        var outcome = await Generate(db, temp.Path, new ObjectName("dbo", "p_extra"));
        Assert.True(outcome.Success, outcome.Message);
        Assert.True(outcome.Validation.Passed, string.Join("; ", outcome.Validation.Problems));

        var part = Assert.Single(outcome.Files, f => f.IsObjectFile);
        Assert.Equal(DestructiveGenerator.Folder, part.Folder);
        Assert.EndsWith("DROP PROCEDURE [dbo].[p_extra]\r\nGO\r\n", ScriptWriter.ReadBack(part.FullPath));
        Assert.Empty(outcome.HeldBack);
        foreach (var f in outcome.Files.Where(f => f.Kind is not WrittenFileKind.Runner && f.RelativePath != ScriptValidator.ReportFile))
        {
            var text = File.ReadAllText(f.FullPath);
            // (p_extra's own rollback text names its type and function; nothing else may appear)
            foreach (var other in new[] { "Kept", "ExtraChild", "v_extra", "syn_extra", "seq_extra", "extra_col", "CK_Child_qty", "UQ_Child_parent" })
                Assert.DoesNotContain(other, text);
        }
    }
}
